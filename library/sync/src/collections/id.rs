use core::sync::atomic::Ordering;

use atomig::{Atom, AtomInteger, Atomic, impls::PrimitiveAtomInteger};
use crossbeam_queue::SegQueue;

/// A thread-safe ID allocator that supports recycling of freed IDs.
///
/// # Type Parameters
///
/// - `T`: The type of IDs to allocate. Must implement `Atom`, `AtomInteger`,
///   and `Copy`. Additionally, the underlying representation of `T` must
///   implement `PrimitiveAtomInteger`.
///
/// # Examples
///
/// ```
/// use libakarin_sync::collections::IdAllocator;
/// let allocator = IdAllocator::new(0u32, 1);
/// let id1 = allocator.allocate();
/// let id2 = allocator.allocate();
/// assert_eq!(id1, 0);
/// assert_eq!(id2, 1);
/// allocator.recycle(id1);
/// let id3 = allocator.allocate();
/// assert_eq!(id3, 0); // Recycled ID is reused
/// ```
pub struct IdAllocator<T>
where
    T: Atom + AtomInteger + Copy,
    T::Repr: PrimitiveAtomInteger,
{
    step: T,
    next_id: Atomic<T>,
    recycled_ids: SegQueue<T>,
}

impl<T> IdAllocator<T>
where
    T: Atom + AtomInteger + Copy,
    T::Repr: PrimitiveAtomInteger,
{
    /// Create a new `IdAllocator` starting from `next_id` and incrementing by
    /// `step`.
    ///
    /// # Arguments
    ///
    /// - `next_id`: The initial ID to allocate.
    /// - `step`: The increment step for generating new IDs.
    pub fn new(next_id: T, step: T) -> Self {
        Self {
            step,
            next_id: Atomic::new(next_id),
            recycled_ids: SegQueue::new(),
        }
    }

    /// Allocate a new ID. If there are recycled IDs available, one of them will
    /// be returned. Otherwise, a new ID will be generated by incrementing
    /// the `next_id` by `step`.
    pub fn allocate(&self) -> T {
        if let Some(id) = self.recycled_ids.pop() {
            id
        } else {
            self.next_id.fetch_add(self.step, Ordering::Relaxed)
        }
    }

    /// Recycle an ID that is no longer in use, making it available for future
    /// allocations.
    ///
    /// # Arguments
    ///
    /// - `id`: The ID to recycle.
    pub fn recycle(&self, id: T) {
        self.recycled_ids.push(id);
    }
}
